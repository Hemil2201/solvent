// Release signing lives outside the repo entirely (~/expense-splitter-keystore/)
// so the keystore and its passwords can never end up in git. Debug builds
// don't need this — only present when building a release APK.
val keystorePropsFile = file(System.getProperty("user.home") + "/expense-splitter-keystore/keystore.properties")
val keystoreProps = Properties().apply {
    if (keystorePropsFile.exists()) load(keystorePropsFile.inputStream())
}

android {
    namespace = "com.expensesplitter.app"
    compileSdk = 34

    defaultConfig {
        applicationId = "com.expensesplitter.app"
        minSdk = 26
        targetSdk = 34
        versionCode = 1
        versionName = "0.1.0"

        // 10.0.2.2 is the Android emulator's alias for the host machine's
        // localhost. A physical device needs the host's LAN IP instead —
        // override via -PapiBaseUrl=http://<lan-ip>:8000/ when building.
        val apiBaseUrl = project.findProperty("apiBaseUrl") as String? ?: "http://10.0.2.2:8000/"
        buildConfigField("String", "API_BASE_URL", "\"$apiBaseUrl\"")
    }

    signingConfigs {
        if (keystorePropsFile.exists()) {
            create("release") {
                storeFile = file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = false
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            if (keystorePropsFile.exists()) {
                signingConfig = signingConfigs.getByName("release")
            }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }
}

